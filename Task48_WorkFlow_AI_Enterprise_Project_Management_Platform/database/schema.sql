
CREATE TABLE users(
id SERIAL PRIMARY KEY,
name VARCHAR(100),
role VARCHAR(50)
);

CREATE TABLE projects(
id SERIAL PRIMARY KEY,
name VARCHAR(100),
status VARCHAR(50)
);

CREATE TABLE tasks(
id SERIAL PRIMARY KEY,
title VARCHAR(200),
priority VARCHAR(50),
status VARCHAR(50)
);

CREATE TABLE teams(
id SERIAL PRIMARY KEY,
name VARCHAR(100)
);

CREATE TABLE comments(
id SERIAL PRIMARY KEY,
task_id INT,
comment TEXT
);

CREATE TABLE documents(
id SERIAL PRIMARY KEY,
name VARCHAR(100)
);

CREATE TABLE notifications(
id SERIAL PRIMARY KEY,
message TEXT
);

CREATE TABLE activity_logs(
id SERIAL PRIMARY KEY,
action TEXT
);
